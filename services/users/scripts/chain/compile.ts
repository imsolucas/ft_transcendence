// Compiles contracts/TournamentScores.sol with solcjs and writes the ABI and bytecode to
// src/chain/artifact.ts (committed, so the Docker image needs neither solc nor contracts/).
//
//   npm run chain:compile           write the artifact
//   npm run chain:compile -- --check  fail if the committed artifact is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const here = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.resolve(here, "../../../../contracts/TournamentScores.sol");
const OUT = path.resolve(here, "../../src/chain/artifact.ts");
// Avalanche C-Chain (and Fuji) support Shanghai+, but "paris" (no PUSH0) runs on every EVM chain.
const EVM_VERSION = "paris";

export function compile(): { abi: unknown[]; bytecode: string; compiler: string } {
  const input = {
    language: "Solidity",
    sources: { "TournamentScores.sol": { content: fs.readFileSync(SOURCE, "utf8") } },
    settings: {
      evmVersion: EVM_VERSION,
      optimizer: { enabled: true, runs: 200 },
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
    },
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input))) as {
    errors?: { severity: string; formattedMessage: string }[];
    contracts: Record<string, Record<string, { abi: unknown[]; evm: { bytecode: { object: string } } }>>;
  };
  const problems = output.errors ?? [];
  // warnings fail the build too: the contract must compile cleanly
  if (problems.length) {
    for (const e of problems) process.stderr.write(`${e.formattedMessage}\n`);
    throw new Error(`solc reported ${problems.length} problem(s)`);
  }
  const c = output.contracts["TournamentScores.sol"].TournamentScores;
  return { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}`, compiler: solc.version() };
}

function render(a: ReturnType<typeof compile>): string {
  return (
    `// GENERATED by scripts/chain/compile.ts from contracts/TournamentScores.sol. Do not edit.\n` +
    `// solc ${a.compiler}, evmVersion ${EVM_VERSION}, optimizer 200 runs.\n` +
    `export const TOURNAMENT_SCORES_ABI = ${JSON.stringify(a.abi, null, 2)} as const;\n\n` +
    `export const TOURNAMENT_SCORES_BYTECODE = "${a.bytecode}";\n`
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(compile());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== text) {
      process.stderr.write("src/chain/artifact.ts is out of date: run npm run chain:compile\n");
      process.exit(1);
    }
    process.stdout.write("artifact up to date\n");
  } else {
    fs.writeFileSync(OUT, text);
    process.stdout.write(`wrote ${path.relative(process.cwd(), OUT)}\n`);
  }
}
